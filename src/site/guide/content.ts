/** Главы и разделы для роли; null — всё. */
export function chaptersFor(role: GuideRole | null): GuideChapter[] {
  if (!role) return CHAPTERS
  return CHAPTERS.filter((c) => c.roles.includes(role))
    .map((c) => ({ ...c, sections: c.sections.filter((s) => !s.roles || s.roles.includes(role)) }))
    .filter((c) => c.sections.length > 0)
}

/** Ширина и высота картинки — у <img>, чтобы страница не прыгала, пока картинки грузятся. */
export function imageSize(src: string): { width?: number; height?: number } {
  const size = SIZES[src]
  return size ? { width: size[0], height: size[1] } : {}
}

/** Все картинки руководства — для проверки, что файлы на месте. */
export function allImages(): GuideImage[] {
  return CHAPTERS.flatMap((c) => c.sections.flatMap((s) => (s.image ? [s.image] : [])))
}
