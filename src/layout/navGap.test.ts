import { describe, expect, it } from 'vitest'

import { navLift } from './navGap'

describe('navLift — на сколько нижнее меню выше настоящего низа экрана', () => {
  it('меню у низа — 0', () => {
    expect(navLift([844, 844, 844], 844, 0)).toBe(0)
  })

  it('iPhone поставил fixed-низ выше: зазор — до самого нижнего из известных низов экрана', () => {
    // Safari: окно 844, видимая часть до 844, меню кончается на 764 — 80px полосы под меню
    expect(navLift([844, 764, 844], 764, 0)).toBe(80)
    // После клавиатуры видимая часть сдвинута на 240px ниже окна
    expect(navLift([604, 604, 844], 604, 0)).toBe(240)
  })

  it('уже опустили меню — замер не обнуляется и меню не прыгает обратно', () => {
    // Опустили на 80: меню теперь кончается у 844, но «стоит» оно по-прежнему на 764
    expect(navLift([844, 764, 844], 844, 80)).toBe(80)
  })

  it('дрожание в пару пикселей и пустые замеры — не зазор', () => {
    expect(navLift([846, 0, Number.NaN], 844, 0)).toBe(0)
  })
})
