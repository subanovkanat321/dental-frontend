export function posterBySlug(slug: string | null | undefined): Poster | undefined {
  return POSTERS.find((p) => p.slug === slug)
}

/** Плакат к теме презентации (кнопка «Плакат» на слайдах). */
export function posterForTopic(topic: TopicSlug): Poster | undefined {
  return POSTERS.find((p) => p.topics.includes(topic))
}

