export function posterCover(p: Poster): ShotName {
  if (p.kind === 'anatomy') return p.shot
  return p.slug === 'caries' ? 'caries-4' : p.slug === 'gums' ? 'perio' : p.slug === 'replace' ? 'fix-implant' : p.panels[0]!.shot
}

