import type { Part } from './callouts'
import type { L, TopicSlug } from './catalog'
import type { ShotName } from './shots.gen'

/**
 * Плакаты «Для пациента» — как настенная таблица у врача: крупная картинка из нашего 3D-атласа, на ней
 * пронумерованные подписи, рядом — что это. Врач показывает на экране или ТВ и объясняет «вот здесь…».
 * Картинки — те же кадры 3D, что у презентаций (scripts/learn-art.mjs → public/content/learn), подписи —
 * по точкам кадра (shots.gen.ts). Тексты — общая информация, без диагнозов, обещаний и цен; кыргызский
 * перед показом пациентам должен проверить носитель языка (как и у презентаций, topics.tsx).
 *
 * Два вида: «строение» — одна большая картинка и легенда с номерами; «стадии» — несколько картинок в ряд
 * (что происходит по шагам или из чего выбрать), у каждой — номер, название и пара строк.
 */
export type PosterSlug = 'tooth' | 'caries' | 'gums' | 'replace' | 'wisdom'

/**
 * Подпись на картинке: часть кадра; label — своё название вместо общего (callouts.ts); at — своя точка
 * (доли ширины и высоты кадра), если точка из shots.gen.ts неудобна для указки.
 */
export type Mark = { part: Part; label?: L; at?: readonly [number, number] }
/** Строка легенды плаката «строение»: подпись на картинке с номером и пояснение. */
export type LegendRow = Mark & { text: L }
export type Panel = { shot: ShotName; title: L; text: L; marks: Mark[]; alt: L }

export type Poster = {
  slug: PosterSlug
  title: L
  lead: L
  note?: L
  /** Тема презентации, из которой плакат открывается кнопкой «Плакат» */
  topics: TopicSlug[]
} & ({ kind: 'anatomy'; shot: ShotName; alt: L; legend: LegendRow[] } | { kind: 'stages'; panels: Panel[] })

