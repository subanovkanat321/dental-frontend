/**
 * Цвета врачей — по порядку, различимы рядом и на светлой, и на тёмной теме; на каждом белые буквы аватара читаются
 * (≥3:1 для крупного полужирного). С 2026-11-20 (шаг 6А) их 10, а не 6: полоска цвета врача у записи в «Все врачи» —
 * седьмой врач не должен совпасть с первым. Первые шесть прежние — у врачей с 1-го по 6-й цвет не поменялся.
 */
export const AVATARS = ['#0E8A80', '#5B7FD6', '#C2793B', '#8E5BB5', '#2F8F5B', '#C2506B', '#3A8DB8', '#857A2C', '#6E7C91', '#9E5B3D']

/**
 * Цвет врача — по месту в списке врачей клиники (`doctors` — список с сервера, не порядок на экране):
 * поменяли порядок колонок — цвет у врача тот же. Один и тот же цвет на компьютере (шапка колонки,
 * чипы) и на телефоне (кружок в шапке, полоска у записей). Врача нет в списке — первый цвет.
 */
export function colorOf(doctors: readonly { id?: number }[], id: number | null | undefined): string {
  const i = doctors.findIndex((d) => d.id === id)
  return AVATARS[Math.max(0, i) % AVATARS.length]!
}

/** «Каримова Динара» → «КД», «Нурболот» → «Н». */
export function initials(name = ''): string {
  return name.split(/\s+/).filter(Boolean).slice(0, 2).map((w) => w[0]).join('').toUpperCase()
}

/**
 * Специальность врача для шапки колонки «Дня» — первая строка «Кратко о себе» (там пишут «Ортодонт,
 * брекеты»): отдельного поля специальности нет, а пациентам эту строку уже показывают.
 */
export function specialtyOf(about: string | undefined): string {
  return (about ?? '').trim().split(/\r?\n/)[0]!.trim()
}
