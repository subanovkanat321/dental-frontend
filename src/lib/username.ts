/**
 * Логин для входа на сайт (V264 бэкенда, Usernames): правила — как на сервере, здесь только подсказка до отправки;
 * последнее слово за сервером (422 на поле username, 409 username-taken).
 */
export const USERNAME_RULES = 'Латинские буквы, цифры, точка, дефис и подчёркивание, 3–32 символа, хотя бы одна буква. '
  + 'Большие и маленькие буквы не различаются.'

/** Что не так с логином; подходит или пусто — пустая строка. */
export function usernameProblem(value: string): string {
  const u = value.trim()
  if (!u) return ''
  if (u.length < 3 || u.length > 32) return 'Логин — от 3 до 32 символов'
  if (!/^[A-Za-z0-9._-]+$/.test(u)) return 'Логин — только латинские буквы, цифры, точка, дефис и подчёркивание'
  if (!/[A-Za-z]/.test(u)) return 'В логине нужна хотя бы одна латинская буква — иначе его не отличить от номера телефона'
  return ''
}

/** В поле «Логин или телефон» — логин (есть латинская буква), а не номер. */
export function isUsername(text: string): boolean {
  return /[A-Za-z]/.test(text)
}
