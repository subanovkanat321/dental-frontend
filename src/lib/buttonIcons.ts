/** Значок для подписи. Подпись уже с «＋» — значок не нужен: плюс и есть значок. */
function iconOf(label: string): string | undefined {
  const text = label.replace(/\s+/g, ' ').trim()
  if (/^[＋+]/.test(text)) return undefined
  return ICONS[text]
}

function decorate(el: Element): void {
  const icon = iconOf(el.textContent ?? '')
  if (icon) {
    if (el.getAttribute('data-ico') !== icon) el.setAttribute('data-ico', icon)
  } else if (el.hasAttribute('data-ico')) {
    el.removeAttribute('data-ico')
  }
}

/** Следить за кнопками и переключателями всего приложения: появились или сменили подпись — поставить значок. */
export function startButtonIcons(root: HTMLElement = document.body): () => void {
  const all = () => root.querySelectorAll('.btn, .segments button').forEach(decorate)
  all()
  let queued = false
  const observer = new MutationObserver(() => {
    if (queued) return
    queued = true
    requestAnimationFrame(() => {
      queued = false
      all()
    })
  })
  observer.observe(root, { childList: true, subtree: true, characterData: true })
  return () => observer.disconnect()
}
