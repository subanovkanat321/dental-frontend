/**
 * Имя рядом с номером в скопированном тексте («Айгуль Маратовна\n+996 555 …»): буквы без номера и меток
 * вроде «тел.». Нет букв или текст длинный (скопировали абзац) — пусто: имя впишут сами.
 */
export function nameFromText(text: string): string {
  const rest = text.replace(/(?:\+|\b00)?[ \t(]*\d[\d \t().-]*\d/g, ' ')
    .replace(/(^|\s)(тел|моб|телефон|phone|tel|mobile|номер)\.?:?(?=\s|$)/giu, ' ')
    .replace(/[^\p{L}\p{M}' -]+/gu, ' ').replace(/\s+/g, ' ').trim()
  return /\p{L}/u.test(rest) && rest.length <= 60 ? rest : ''
}
