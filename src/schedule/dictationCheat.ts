// Шпаргалка диктовки: что сказать по порядку и простые отметки «уже сказано» по распознанному тексту.

/** Что сказать по порядку — врач почти читает с экрана. */
export const CHEAT_STEPS: { title: string; say: string; done?: (text: string) => boolean }[] = [
  { title: 'Зуб и что было', say: '«Тридцать шестой зуб — кариес»', done: (t) => teethSaid(t).size > 0 },
  { title: 'Что сделали', say: '«Поставили пломбу» / «Лечили каналы» / «Удалили»', done: (t) => /пломб|канал|удал|корон|лечил|лечен|постав/i.test(t) },
  { title: 'Другие зубы, если есть', say: '«Сорок шестой — каналы, в следующий раз»', done: (t) => teethSaid(t).size > 1 },
  { title: 'Заметка, по желанию', say: '«Пациент жаловался на чувствительность»' },
  { title: 'Следующий визит', say: '«Контроль через две недели»', done: (t) => /через|следующ|контрол/i.test(t) },
]

const UNITS = ['перв', 'втор', 'трет', 'четв', 'пят', 'шест', 'седьм', 'восьм']
const TEENS = ['одиннадцат', 'двенадцат', 'тринадцат', 'четырнадцат', 'пятнадцат', 'шестнадцат', 'семнадцат', 'восемнадцат']
const TENS: [RegExp, number][] = [[/двадцат\S*\s+/, 2], [/тридцат\S*\s+/, 3], [/сорок\S*\s+/, 4]]

/**
 * Номера зубов (11–48), которые прозвучали: цифрами («36-й») и словами («тридцать шестой»).
 * Числа перед «дней/недель/минут…» — не зубы («через 14 дней»). Только для отметок шпаргалки:
 * ошибётся — врач увидит лишнюю ✓, ничего не сохранится.
 */
export function teethSaid(text: string): Set<number> {
  const t = text.toLowerCase().replace(/ё/g, 'е')
  const found = new Set<number>()
  for (const m of t.matchAll(/(?:^|\D)([1-4][1-8])(?!\d)(?!\s*(?:дн|день|недел|мин|час|мес|раз|лет|год|%))/g)) found.add(Number(m[1]))
  TEENS.forEach((w, i) => { if (t.includes(w)) found.add(11 + i) })
  for (const [tens, d] of TENS) {
    for (const m of t.matchAll(new RegExp(tens.source + '(' + UNITS.join('|') + ')', 'g'))) {
      found.add(d * 10 + UNITS.indexOf(m[1]!) + 1)
    }
  }
  return found
}
