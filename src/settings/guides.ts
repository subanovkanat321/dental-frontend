/** Своя роль открывается первой: ассистент → врач → регистратура → администратор. */
export function ownRole(me: Me): Role {
  if (isAssistant(me)) return 'assistant'
  if (me.doctorId != null) return 'doctor'
  if (me.reception) return 'reception'
  if (me.admin) return 'admin'
  return 'reception'
}

/**
 * Роль для «Руководства Tish» (/guide?role=…): админу — его глава «Настройки клиники» и всё
 * остальное, даже если он и врач; иначе — как в «Памятке».
 */
export function guideRole(me: Me): Role {
  return me.admin ? 'admin' : ownRole(me)
}

/** Адрес полного руководства с картинками — страница сайта, открывается без входа. */
export function guideUrl(role: Role): string {
  // from=app — открыли из CRM: на странице кнопка «Вернуться в Tish» вместо «Назад» сайта
  return `${window.location.origin}/guide?role=${role}&from=app`
}
