/**
 * Вкладка объединённого пункта «Настроек» — бывший отдельный пункт (свой экран, свои права, свой ключ). Ключ —
 * прежний ключ пункта: по нему RENDER рисует экран, и старый адрес #/settings/<ключ> открывает эту вкладку.
 */
export type SettingsTab = {
  key: string
  /** Название вкладки (и прежнее название пункта — по нему ищут в руководстве) */
  title: string
  /** Короче — на телефоне, где вкладки делят 390px */
  short?: string
  show: (me: Me) => boolean
}

const doctorOrAdmin = (me: Me) => Boolean(me.admin || me.doctorId != null)

function tab(key: string, title: string, show: SettingsTab['show'], short?: string): SettingsTab {
  return { key, title, show, short }
}

/** Пункт с вкладками: виден, если видна хоть одна вкладка (у каждой — права прежнего пункта). */
function tabbed(key: string, title: string, hint: string, tabs: SettingsTab[]): SettingsItem {
  return { key, title, hint, show: (me) => tabs.some((t) => t.show(me)), tabs }
}

