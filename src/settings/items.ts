/** Прежний пункт «Настроек» (вкладка) → пункт, где он теперь: lib/route ведёт старый адрес туда, меню подсвечивает пункт. */
export const SETTINGS_ALIAS: Record<string, string> = Object.fromEntries(
  SETTINGS_GROUPS.flatMap(([, list]) => list.flatMap((i) => (i.tabs ?? []).map((t) => [t.key, i.key]))),
)

/** Виден ли этой роли пункт или вкладка «Настроек» по ключу (советы дня: показывать ли совет про экран). */
export function settingsVisible(me: Me, key: string): boolean {
  for (const [, list] of SETTINGS_GROUPS) {
    for (const i of list) {
      if (i.key === key) return i.show(me)
      const t = i.tabs?.find((x) => x.key === key)
      if (t) return t.show(me)
    }
  }
  return false
}

