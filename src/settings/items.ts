import { isAssistant, seesAllMoney } from '../lib/roles'

type Me = Schemas['BookingViewsMe']

/**
 * Пункты «Настроек» без их экранов: название, подсказка, кому видно. Отдельно от SettingsPage,
 * потому что их показывает и меню слева (дерево подразделов), а меню не должно тянуть код
 * экранов «Настроек» — он грузится отдельным кусочком, только когда «Настройки» открыли.
 */
export type SettingsItem = {
  key: string
  title: string
  hint: string
  show: (me: Me) => boolean
  /** Не в списке, но открывается по адресу (старые ссылки, кнопки бота) */
  hidden?: boolean
  /** Не свой экран, а ссылка на раздел меню (в дереве не показываем — раздел и так в меню) */
  section?: Page
}

/** Значки пунктов — как в меню прежнего приложения. */
export const SETTINGS_EMOJI: Record<string, string> = { 'about': '🏥', 'doctors': '👩‍⚕️', 'services': '🦷', 'hours': '🕘', 'reminder': '🔔', 'questions': '🩺', 'memos': '📋', 'learn': '📖', 'patient-news': '📰', 'sources': '📣', 'plan': '💳', 'agreement': '📄', 'data': '📦', 'ai': '✨', 'profile': '🧑‍⚕️', 'appearance': '🎨', 'calendar': '📅', 'guide': '📘', 'support': '🛟', 'survey': '📝', 'privacy': '🔒', 'contract': '✍️', 'chairs': '🪑' }

const all = () => true
const admin = (me: Me) => Boolean(me.admin)

function item(key: string, title: string, hint: string, show: SettingsItem['show'], extra?: Partial<SettingsItem>): SettingsItem {
  return { key, title, hint, show, ...extra }
}

