import type { Schemas } from '../api/client'
import { isAssistant, seesAllMoney } from '../lib/roles'

type Me = Schemas['BookingViewsMe']

/**
 * Пункты «Настроек», «Клиники», блока «Я» и «Помощи» без их экранов: название, подсказка, кому видно. Отдельно от SettingsPage,
 * потому что их показывает и меню слева (дерево подразделов), а меню не должно тянуть код
 * экранов «Настроек» — он грузится отдельным кусочком, только когда «Настройки» открыли.
 */
export type SettingsItem = {
  key: string
  title: string
  hint: string
  show: (me: Me) => boolean
  /** Не в списке, но открывается по адресу (старые ссылки, кнопки бота) */
  hidden?: boolean
}

/** Значки пунктов — как в меню прежнего приложения (только в списке на главной «Настроек», не в меню). */
export const SETTINGS_EMOJI: Record<string, string> = { 'reminder': '🔔', 'questions': '🩺', 'memos': '📋', 'patient-news': '📰', 'sources': '📣', 'plan': '💳', 'agreement': '📄', 'data': '📦', 'ai': '✨', 'contract': '✍️' }

const all = () => true
const admin = (me: Me) => Boolean(me.admin)

function item(key: string, title: string, hint: string, show: SettingsItem['show'], extra?: Partial<SettingsItem>): SettingsItem {
  return { key, title, hint, show, ...extra }
}

